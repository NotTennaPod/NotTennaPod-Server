func ids(items []Item) string {
	var b strings.Builder
	for _, it := range items {
		b.WriteString(it.EpisodeID)
	}
	return b.String()
}

func TestComparatorsAreStable(t *testing.T) {
	items := []Item{
		{EpisodeID: "a", Title: "Beta", Duration: 10, PublicationTime: 3},
		{EpisodeID: "b", Title: "alpha", Duration: 5, PublicationTime: 0},
		{EpisodeID: "c", Title: "beta", Duration: 10, PublicationTime: 3},
		{EpisodeID: "d", Title: "", Duration: 0, PublicationTime: 1},
	}
	for order, want := range map[string]string{
		"episode_title_a_z":   "dbac", // "" first; "Beta" and "beta" tie and keep their order
		"episode_title_z_a":   "acbd",
		"duration_short_long": "dbac",
		"duration_long_short": "acbd",
		"date_old_new":        "bdac",
		"date_new_old":        "acdb",
		"feed_title_a_z":      "abcd", // all empty: current order
	} {
		got, err := Sort(order, items)
		if err != nil || ids(got) != want {
			t.Errorf("%s: %s %v, want %s", order, ids(got), err, want)
		}
	}
	if _, err := Sort("random", items); err != ErrNotDeterministic {
		t.Errorf("random: %v", err)
	}
}

func TestTitleCollation(t *testing.T) {
	// Simple lowercase mapping per code point, then code point order:
	// "İ" (U+0130) maps to "i"; "É" to "é", which sorts after ASCII letters.
	items := []Item{{EpisodeID: "1", Title: "Éa"}, {EpisodeID: "2", Title: "İb"}, {EpisodeID: "3", Title: "ia"}, {EpisodeID: "4", Title: "Z"}}
	got, _ := Sort("episode_title_a_z", items)
	if ids(got) != "3241" {
		t.Fatalf("collation: %s", ids(got))
	}
}

// The example in FeedItemPermutors.smartShuffle's documentation (ABCDDEEEEEEEEEE).
// Its diagrams are illustrative; Android's loop, traced by hand, places E at
// slots 1,2,4,5,6,8,9,10,12,13 (spread 15/11), D at 3 and 11 (spread 5/3), then
// the single episodes: A at 7 (spread 3/2), B at 0, C at 14.
func TestSmartShuffleMatchesAndroid(t *testing.T) {
	var items []Item
	n := 0
	for _, p := range []struct {
		podcast string
		count   int
	}{{"A", 1}, {"B", 1}, {"C", 1}, {"D", 2}, {"E", 10}} {
		for i := 0; i < p.count; i++ {
			n++
			items = append(items, Item{EpisodeID: p.podcast, PodcastID: p.podcast, PublicationTime: int64(n)})
		}
	}
	got, _ := Sort("smart_shuffle_old_new", items)
	if ids(got) != "BEEDEEEAEEEDEEC" {
		t.Fatalf("smart shuffle: %s", ids(got))
	}
	// Within a podcast, publication order (ascending, then descending).
	last := int64(0)
	for _, it := range got {
		if it.PodcastID == "E" {
			if it.PublicationTime < last {
				t.Fatal("E not ascending")
			}
			last = it.PublicationTime
		}
	}
}

func TestRekeyKeepsALongestIncreasingRun(t *testing.T) {
	r := rand.New(rand.NewPCG(5, 6))
	newID := func() [16]byte {
		var u [16]byte
		for i := range u {
			u[i] = byte(r.IntN(256))
		}
		return u
	}
	for trial := 0; trial < 200; trial++ {
		// A queue of random keys, in key order; then a random sorted order.
		n := 1 + r.IntN(30)
		var ps []Placed
		var low *contract.QueueKey
		for i := 0; i < n; i++ {
			u := newID()
			k, err := contract.QueueKeyBetween(low, nil, u)
			if err != nil {
				t.Fatal(err)
			}
			ps = append(ps, Placed{Item: Item{EpisodeID: fmt.Sprint(i)}, Key: k, PositionID: u})
			low = &ps[len(ps)-1].Key
		}
		r.Shuffle(len(ps), func(i, j int) { ps[i], ps[j] = ps[j], ps[i] })
		out, err := Rekey(ps, newID)
		if err != nil {
			t.Fatal(err)
		}
		kept := 0
		for i := range out {
			if i > 0 && contract.CompareQueueKeys(out[i-1].Key, out[i].Key) >= 0 {
				t.Fatalf("trial %d: keys not increasing at %d", trial, i)
			}
			if out[i].EpisodeID != ps[i].EpisodeID {
				t.Fatalf("trial %d: order changed", trial)
			}
			if contract.CompareQueueKeys(out[i].Key, ps[i].Key) == 0 && out[i].PositionID == ps[i].PositionID {
				kept++
			}
		}
		if want := lisLength(ps); kept != want {
			t.Fatalf("trial %d: kept %d keys, longest increasing run %d", trial, kept, want)
		}
	}
}

func lisLength(ps []Placed) int {
	best := make([]int, len(ps))
	longest := 0
	for i := range ps {
		best[i] = 1
		for j := 0; j < i; j++ {
			if contract.CompareQueueKeys(ps[j].Key, ps[i].Key) < 0 && best[j]+1 > best[i] {
				best[i] = best[j] + 1
			}
		}
		longest = max(longest, best[i])
	}
	return longest
}

// The shared canonical comparator vectors (contract/vectors/queue_sort.json,
// generated by the independent Python reference): every keep-sorted order.
func TestSharedComparatorVectors(t *testing.T) {
	data, err := os.ReadFile("../../contract/vectors/queue_sort.json")
	if err != nil {
		t.Fatal(err)
	}
	var suite struct {
		Suite string
		Cases []struct {
			Description string
			Items       []struct {
				Title           string `json:"title"`
				PodcastID       string `json:"podcast_id"`
				PodcastTitle    string `json:"podcast_title"`
				PublicationTime int64  `json:"publication_time"`
				Duration        int64  `json:"duration"`
			}
			Output map[string][]int
		}
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	if err := dec.Decode(&suite); err != nil {
		t.Fatal(err)
	}
	if suite.Suite != "queue_sort" || len(suite.Cases) == 0 {
		t.Fatalf("bad suite %q with %d cases", suite.Suite, len(suite.Cases))
	}
	for _, c := range suite.Cases {
		items := make([]Item, len(c.Items))
		for i, it := range c.Items {
			items[i] = Item{EpisodeID: fmt.Sprint(i), Title: it.Title, PodcastID: it.PodcastID, PodcastTitle: it.PodcastTitle,
				PublicationTime: it.PublicationTime, Duration: it.Duration}
		}
		for order, want := range c.Output {
			got, err := Sort(order, items)
			if err != nil {
				t.Fatalf("%s / %s: %v", c.Description, order, err)
			}
			var idx []int
			for _, it := range got {
				var n int
				fmt.Sscan(it.EpisodeID, &n)
				idx = append(idx, n)
			}
			if fmt.Sprint(idx) != fmt.Sprint(want) && !(len(idx) == 0 && len(want) == 0) {
				t.Errorf("%s / %s: %v, want %v", c.Description, order, idx, want)
			}
		}
	}
}
