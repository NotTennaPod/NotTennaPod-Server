// Command gentagsoup writes internal/feed/tagsoup_schema.go, the element and
// entity tables of TagSoup's HTMLSchema as Android 16 ships it
// (platform/external/tagsoup). It reads HTMLSchema.java, HTMLModels.java and
// Schema.java from -src, or fetches them from AOSP at the pinned commit.
//
//	go run ./internal/gentagsoup -out tagsoup_schema.go
package main

import (
	"bytes"
	"encoding/base64"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// The android16-release head of platform/external/tagsoup.
const (
	ref  = "e55b6311e644c0df77cdb0fded945e53c5890bc8"
	base = "https://android.googlesource.com/platform/external/tagsoup/+/" + ref + "/src/org/ccil/cowan/tagsoup/"
)

var (
	reConst   = regexp.MustCompile(`public static final int ([MF]_\w+) = ([^;]+);`)
	reElement = regexp.MustCompile(`(?m)^\s*elementType\("([^"]+)", ([^,]+), ([^,]+), ([^)]+)\);`)
	reParent  = regexp.MustCompile(`(?m)^\s*parent\("([^"]+)", "([^"]+)"\);`)
	reEntity  = regexp.MustCompile(`(?m)^\s*entity\("([^"]+)", 0x([0-9A-Fa-f]+)\);`)
)

func main() {
	src := flag.String("src", "", "directory with HTMLSchema.java, HTMLModels.java and Schema.java (default: fetch from AOSP)")
	out := flag.String("out", "tagsoup_schema.go", "output file")
	flag.Parse()

	read := func(name string) string {
		if *src != "" {
			b, err := os.ReadFile(filepath.Join(*src, name))
			if err != nil {
				log.Fatal(err)
			}
			return string(b)
		}
		resp, err := http.Get(base + name + "?format=TEXT")
		if err != nil {
			log.Fatal(err)
		}
		defer resp.Body.Close()
		if resp.StatusCode != http.StatusOK {
			log.Fatalf("%s: %s", name, resp.Status)
		}
		b, err := io.ReadAll(base64.NewDecoder(base64.StdEncoding, resp.Body))
		if err != nil {
			log.Fatal(err)
		}
		return string(b)
	}
	schema, models, abstract := read("HTMLSchema.java"), read("HTMLModels.java"), read("Schema.java")

	consts := map[string]uint32{}
	for _, m := range reConst.FindAllStringSubmatch(abstract+models, -1) {
		consts[m[1]] = eval(m[2], consts)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gentagsoup from AOSP platform/external/tagsoup %s\n", ref)
	b.WriteString("// (HTMLSchema.java, HTMLModels.java, Schema.java). DO NOT EDIT.\n\npackage feed\n\n")
	b.WriteString("// tagsoupElementDefs are HTMLSchema's elementType and parent calls, in order:\n")
	b.WriteString("// name, content model, member-of models, flags, natural parent.\n")
	b.WriteString("var tagsoupElementDefs = [...]tagsoupElementDef{\n")
	parents := map[string]string{}
	for _, m := range reParent.FindAllStringSubmatch(schema, -1) {
		parents[m[1]] = m[2]
	}
	elements := reElement.FindAllStringSubmatch(schema, -1)
	for _, m := range elements {
		fmt.Fprintf(&b, "\t{%q, %#08x, %#08x, %d, %q}, // %s; %s; %s\n", m[1], eval(m[2], consts), eval(m[3], consts),
			eval(m[4], consts), parents[m[1]], m[2], m[3], m[4])
	}
	b.WriteString("}\n\n")

	entities := map[string]string{}
	for _, m := range reEntity.FindAllStringSubmatch(schema, -1) {
		entities[m[1]] = m[2] // a repeated name replaces the earlier one, as in the HashMap
	}
	names := make([]string, 0, len(entities))
	for n := range entities {
		names = append(names, n)
	}
	sort.Strings(names)
	b.WriteString("// tagsoupEntities are HTMLSchema's entity calls: name to code point.\n")
	b.WriteString("var tagsoupEntities = map[string]int32{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: 0x%s,\n", n, strings.ToUpper(entities[n]))
	}
	b.WriteString("}\n")

	if len(elements) == 0 || len(parents) == 0 || len(entities) == 0 {
		log.Fatal("no schema calls found")
	}
	src2, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src2, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d elements, %d parents, %d entities", len(elements), len(parents), len(entities))
}

// eval evaluates a Java int constant expression of names, numbers, 1 << n,
// ~, & and |.
func eval(expr string, consts map[string]uint32) uint32 {
	var v uint32
	for i, alt := range strings.Split(expr, "|") {
		var a uint32 = 0xFFFFFFFF
		for _, f := range strings.Split(alt, "&") {
			a &= factor(strings.TrimSpace(f), consts)
		}
		if i == 0 {
			v = a
		} else {
			v |= a
		}
	}
	return v
}

func factor(f string, consts map[string]uint32) uint32 {
	if strings.HasPrefix(f, "~") {
		return ^factor(strings.TrimSpace(f[1:]), consts)
	}
	if l, r, ok := strings.Cut(f, "<<"); ok {
		return factor(strings.TrimSpace(l), consts) << factor(strings.TrimSpace(r), consts)
	}
	if v, ok := consts[f]; ok {
		return v
	}
	n, err := strconv.ParseUint(f, 0, 32)
	if err != nil {
		log.Fatalf("cannot evaluate %q", f)
	}
	return uint32(n)
}
