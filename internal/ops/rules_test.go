// TestRuleVectors runs every `rules` vector (docs/CONTRACT.md) through the
// server: shared vectors in contract/vectors/rules_*.json and, when present,
// randomized cases in $NTP_RULE_CASES (generated by the Python reference).
func TestRuleVectors(t *testing.T) {
	files, _ := filepath.Glob("../../contract/vectors/rules_*.json")
	// Server-only cases (generated by the reference) beside the shared ones.
	more, _ := filepath.Glob("testdata/*/rules_*.json")
	files = append(files, more...)
	if dir := os.Getenv("NTP_RULE_CASES"); dir != "" {
		more, _ := filepath.Glob(filepath.Join(dir, "*.json"))
		files = append(files, more...)
	}
	if len(files) == 0 {
		t.Skip("no rule vectors yet")
	}
	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			t.Fatal(err)
		}
		v, err := contract.DecodeJSON(data)
		if err != nil {
			t.Fatalf("%s: %v", file, err)
		}
		suite := v.(map[string]any)
		cases, _ := suite["cases"].([]any)
		for i, c := range cases {
			name := strings.TrimSuffix(filepath.Base(file), ".json") + "_" + itoa(i)
			t.Run(name, func(t *testing.T) { runRuleCase(t, c.(map[string]any)) })
		}
	}
}

func itoa(i int) string { b, _ := json.Marshal(i); return string(b) }

func runRuleCase(t *testing.T, c map[string]any) {
	ctx := context.Background()
	store, err := storage.Open(ctx, filepath.Join(t.TempDir(), "data"))
	if err != nil {
		t.Fatal(err)
	}
	defer store.Close()
	box, err := sealed.LoadOrCreate(store.Dir())
	if err != nil {
		t.Fatal(err)
	}
	accountID, namespace := c["account_id"].(string), c["namespace"].(string)
	if err := store.Write(ctx, func(tx *storage.WriteTx) error { _, err := tx.CreateAccountWithIDs(accountID, namespace); return err }); err != nil {
		t.Fatal(err)
	}
	reg := protocol.NewRegistry()
	Register(reg)
	var now int64
	random := &vectorRandom{t: t}
	svc := &protocol.Service{Store: store, Registry: reg, Box: box, Now: func() time.Time { return time.UnixMilli(now) }, Random: random}
	fetches := &vectorFetches{t: t, store: store, svc: svc, account: accountID, namespace: namespace, pending: map[string]startedFetch{},
		stored: map[string]*storedFetch{}, lastSuccess: map[string]int64{}}
	seqs := map[string]int64{}
	gotOutcomes := map[string]any{}
	gotValues := map[string]any{} // live receipts' sort values (PROTOCOL §7.6)
	recov := newVectorRecovery(t, store, svc, accountID, random, func(n int64) { now = n })
	for i, raw := range c["arrivals"].([]any) {
		arr := raw.(map[string]any)
		// Recovery uploads (PROTOCOL §6.11): recovered facts and decisions are joined in
		// requests that end at a recovery_end (or, the reference's
		// unification point, at a recovered identity decision).
		if recov.take(i, arr) {
			continue
		}
		recov.flush(protocol.RecoveryEndSteps{}, nil, 0)
		// An arrival's commit takes seq n, its 1-based position (or its
		// receipt's): arrivals that commit nothing (a fetch start, an unchanged
		// fetch) leave gaps, kept here with empty commits.
		target := int64(i)
		if r, ok := arr["receipt"].(map[string]any); ok {
			seq, _ := r["seq"].(json.Number).Int64()
			epoch, _ := r["epoch"].(json.Number).Int64()
			recov.toEpoch(epoch)
			target = seq - 1
		} else if ds, ok := arr["decisions"].([]any); ok && len(ds) > 0 {
			// The commit the arrival's decisions record (a restored server's
			// epoch, which vectors may state only there).
			d := ds[0].(map[string]any)
			epoch, _ := num64(d["epoch"])
			seq, _ := num64(d["seq"])
			recov.toEpoch(epoch)
			target = seq - 1
		}
		padLog(t, store, accountID, target)
		if fs, ok := arr["fetch_start"].(map[string]any); ok {
			fetches.start(fs)
			continue
		}
		if fx, ok := arr["fetch"].(map[string]any); ok {
			n, _ := arr["receive_time"].(json.Number).Int64()
			now = n
			random.load(i, arr["decisions"])
			fetches.apply(i, fx)
			random.done()
			recov.mid = false
			checkReplay(t, svc, accountID)
			continue
		}
		fact := arr["fact"].(map[string]any)
		author := fact["author_id"].(string)
		var caps []string
		for _, x := range arr["capabilities"].([]any) {
			caps = append(caps, x.(string))
		}
		sort.Strings(caps)
		capJSON, _ := json.Marshal(caps)
		if caps == nil {
			capJSON = []byte("[]")
		}
		err := store.Write(ctx, func(tx *storage.WriteTx) error {
			acct := tx.Account(accountID)
			if _, err := acct.Installation(author); err == nil {
				return acct.UpdateInstallationDevice(author, "d", "1", string(capJSON))
			}
			return acct.InsertInstallation(storage.Installation{InstallID: author, InstanceNonce: author, Name: "d", Platform: "ios",
				AppVersion: "1", Capabilities: string(capJSON)})
		})
		if err != nil {
			t.Fatal(err)
		}
		n, _ := arr["receive_time"].(json.Number).Int64()
		now = n
		a, err := protocol.ParseFact(fact)
		if err != nil {
			t.Fatalf("arrival %d: %v", i, err)
		}
		var head contract.Cursor
		store.Read(ctx, func(r *storage.ReadTx) error {
			h, err := r.Account(accountID).Head()
			head = contract.Cursor{LogID: h.LogID, Epoch: h.Epoch, Seq: h.Seq, Digest: h.Digest}
			return err
		})
		seqs[author]++
		// Vectors assume referenced secrets are held: send them beside the fact.
		var secrets []protocol.Secret
		if payload, ok := fact["payload"].(map[string]any); ok {
			for _, k := range []string{"credentials_secret", "secret_id"} {
				if id, ok := payload[k].(string); ok {
					secrets = append(secrets, protocol.Secret{ID: id, Username: "u", Password: "p"})
				}
			}
		}
		random.load(i, arr["decisions"])
		resp, err := svc.Push(ctx, protocol.PushRequest{AccountID: accountID, Cursor: head, InstallID: author, AckedInstallSeq: seqs[author] - 1,
			Operations: []protocol.PushOp{{InstallSeq: seqs[author], Fact: a}}, Secrets: secrets}, func(tx *storage.WriteTx) (*storage.Installation, error) {
			inst, err := tx.Account(accountID).Installation(author)
			return &inst, err
		})
		if err != nil {
			t.Fatalf("arrival %d: %v", i, err)
		}
		random.done()
		recov.mid = false
		checkReplay(t, svc, accountID) // every prefix (PROTOCOL §7.6)
		r := resp.Results[0]
		if r.Status == "duplicate" || r.Status == "op_id_conflict" {
			continue // a repeated delivery: the original outcome stands
		}
		if r.Status != "accepted" {
			t.Fatalf("arrival %d: status %s", i, r.Status)
		}
		if want, ok := arr["normalized_time"].(json.Number); ok && r.Receipt["normalized_time"].(json.Number) != want && r.Receipt["outcome"] != "rejected" {
			t.Errorf("arrival %d: normalized time %v, vector %v", i, r.Receipt["normalized_time"], want)
		}
		o := map[string]any{"outcome": r.Receipt["outcome"]}
		if reason, ok := r.Receipt["reason"]; ok {
			o["reason"] = reason
		}
		gotOutcomes[fact["op_id"].(string)] = o
		if v, ok := r.Receipt["sort_values"]; ok {
			gotValues[fact["op_id"].(string)] = v
		}
	}
	recov.flush(protocol.RecoveryEndSteps{}, nil, 0)
	if !recov.mid {
		checkReplay(t, svc, accountID) // a case ending inside a request publishes nothing
	}
	expected := c["expected"].(map[string]any)
	// Outcomes.
	for op, want := range expected["outcomes"].(map[string]any) {
		if !sameJSON(gotOutcomes[op], want) {
			t.Errorf("outcome of %s: server %s, vector %s", op, js(gotOutcomes[op]), js(want))
		}
	}
	// Sort values the live receipts recorded (absent: none).
	wantValues, _ := expected["sort_values"].(map[string]any)
	if wantValues == nil {
		wantValues = map[string]any{}
	}
	if !sameJSON(gotValues, wantValues) {
		var diffs []string
		for op, w := range wantValues {
			if !sameJSON(gotValues[op], w) {
				diffs = append(diffs, "  "+op+"\n   server: "+js(gotValues[op])+"\n   vector: "+js(w))
			}
		}
		for op, g := range gotValues {
			if _, ok := wantValues[op]; !ok {
				diffs = append(diffs, "  "+op+"\n   server: "+js(g)+"\n   vector: (none)")
			}
		}
		slices.Sort(diffs)
		t.Errorf("sort values differ:\n%s", strings.Join(diffs, "\n"))
	}
	// Resolutions (podcast.resolution decisions), the decisions the case
	// created and final records.
	gotRes := map[string]any{}
	resRank := map[string][3]string{}
	var gotDecisions []any
	var gotRecords []any
	err = store.Read(ctx, func(r *storage.ReadTx) error {
		acct := r.Account(accountID)
		nodes, err := acct.Nodes()
		if err != nil {
			return err
		}
		for _, n := range nodes {
			if n.Kind != "decision" {
				continue
			}
			b, err := acct.DecisionBytes(n.ID)
			if err != nil {
				return err
			}
			d, _ := contract.DecodeJSON(b)
			dm := d.(map[string]any)
			if dm["decision_type"] == "podcast.resolution" && !rejectedFact(t, acct, dm["subject"].(string)) {
				// The effective resolution: the smallest rank (PROTOCOL §6.11). A
				// registration whose receipt rejects it (a node kept by a provisional receipt) has
				// no resolution.
				subject := dm["subject"].(string)
				rank := [3]string{fmt.Sprintf("%020v", dm["epoch"]), fmt.Sprintf("%020v", dm["seq"]), dm["decision_id"].(string)}
				if old, ok := resRank[subject]; !ok || slices.Compare(rank[:], old[:]) < 0 {
					gotRes[subject], resRank[subject] = dm["result"], rank
				}
			}
			if recov.uploaded[n.ID] {
				continue // uploaded in recovery, not created by the case
			}
			if comparedDecision(dm["decision_type"].(string)) {
				delete(dm, "key_id")
				delete(dm, "mac")
				gotDecisions = append(gotDecisions, dm)
			}
		}
		recs, err := acct.Records(nil)
		for _, x := range recs {
			v, _ := contract.DecodeJSON([]byte(x.Value))
			gotRecords = append(gotRecords, map[string]any{"entity": x.Entity, "id": x.EntityID, "field_group": x.FieldGroup, "value": v})
		}
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	for op, want := range expected["resolutions"].(map[string]any) {
		if !sameJSON(gotRes[op], want) {
			t.Errorf("resolution of %s: server %s, vector %s", op, js(gotRes[op]), js(want))
		}
	}
	if len(gotRes) != len(expected["resolutions"].(map[string]any)) {
		t.Errorf("server made %d resolutions, vector has %d", len(gotRes), len(expected["resolutions"].(map[string]any)))
	}
	sort.Slice(gotDecisions, func(i, j int) bool {
		return gotDecisions[i].(map[string]any)["decision_id"].(string) < gotDecisions[j].(map[string]any)["decision_id"].(string)
	})
	wantDecisions, _ := expected["decisions"].([]any)
	if !sameJSON(gotDecisions, wantDecisions) && !(len(gotDecisions) == 0 && len(wantDecisions) == 0) {
		t.Errorf("decisions differ:\n%s", diffDecisions(gotDecisions, wantDecisions))
	}
	wantRecords := expected["records"].([]any)
	if groups, ok := expected["field_groups"].([]any); ok {
		// Import cases compare only the queue's groups (docs/CONTRACT.md).
		keep := map[string]bool{}
		for _, g := range groups {
			keep[g.(string)] = true
		}
		filtered := []any{}
		for _, r := range gotRecords {
			if keep[r.(map[string]any)["field_group"].(string)] {
				filtered = append(filtered, r)
			}
		}
		gotRecords = filtered
	}
	if !sameJSON(gotRecords, wantRecords) {
		t.Errorf("records differ:\n%s", diffRecords(gotRecords, wantRecords))
	}
	// The rebuild invariant (PROTOCOL §6.11): the case's account rebuilds from its archive.
	if !recov.mid {
		checkRebuild(t, svc, accountID)
		return
	}
	// A case ending inside a recovery request ends between publication
	// boundaries: a rebuild's publication rule then records a layout
	// (PROTOCOL §7.6: "after a rebuild, the publication rule runs"),
	// whose server choices the vector cannot record. Only the queue's
	// published keys may change.
	random.free = true
	report, err := svc.Rebuild(ctx, accountID)
	if err != nil {
		t.Errorf("rebuild after a case ending inside a request: %v\n%s", err, describeRebuild(report))
	}
	for _, r := range report.Changed {
		if r.FieldGroup != "queue_position" {
			t.Errorf("rebuild after a case ending inside a request changed %s/%s/%s", r.Entity, r.ID, r.FieldGroup)
		}
	}
	checkReplay(t, svc, accountID)
}

// rejectedFact reports whether an archived fact's receipt rejects it.
func rejectedFact(t *testing.T, acct *storage.AccountReader, opID string) bool {
	_, receipt, err := acct.FactBytes(opID)
	if errors.Is(err, storage.ErrNotFound) {
		return false
	} else if err != nil {
		t.Fatal(err)
	}
	var r struct {
		Outcome string `json:"outcome"`
	}
	if err := json.Unmarshal(receipt, &r); err != nil {
		t.Fatal(err)
	}
	return r.Outcome == "rejected"
}

func js(v any) string {
	b, _ := contract.Canonical(v)
	return string(b)
}

func sameJSON(a, b any) bool {
	if a == nil || b == nil {
		return a == nil && b == nil
	}
	return js(a) == js(b)
}

// diffDecisions lists the decisions only one side made and, for those both
// made (by decision ID), the members that differ.
func diffDecisions(got, want []any) string {
	index := func(list []any) (map[string]map[string]any, []string) {
		m := map[string]map[string]any{}
		var ids []string
		for _, d := range list {
			dm := d.(map[string]any)
			id := dm["decision_id"].(string)
			m[id] = dm
			ids = append(ids, id)
		}
		return m, ids
	}
	g, gids := index(got)
	w, wids := index(want)
	var out []string
	for _, id := range wids {
		if _, ok := g[id]; !ok {
			out = append(out, "  only in vector: "+js(w[id]))
		}
	}
	for _, id := range gids {
		if _, ok := w[id]; !ok {
			out = append(out, "  only in server: "+js(g[id]))
		}
	}
	for _, id := range gids {
		wd, ok := w[id]
		if !ok {
			continue
		}
		var keys []string
		for k := range wd {
			keys = append(keys, k)
		}
		for k := range g[id] {
			if _, ok := wd[k]; !ok {
				keys = append(keys, k)
			}
		}
		slices.Sort(keys)
		for _, k := range keys {
			if !sameJSON(g[id][k], wd[k]) {
				out = append(out, "  "+wd["decision_type"].(string)+" "+id+" "+k+"\n   server: "+js(g[id][k])+"\n   vector: "+js(wd[k]))
			}
		}
	}
	return strings.Join(out, "\n")
}

func diffRecords(got, want []any) string {
	key := func(r any) string {
		m := r.(map[string]any)
		return m["entity"].(string) + "/" + m["id"].(string) + "/" + m["field_group"].(string)
	}
	g, w := map[string]string{}, map[string]string{}
	for _, r := range got {
		g[key(r)] = js(r.(map[string]any)["value"])
	}
	for _, r := range want {
		w[key(r)] = js(r.(map[string]any)["value"])
	}
	var keys []string
	for k := range g {
		keys = append(keys, k)
	}
	for k := range w {
		if _, ok := g[k]; !ok {
			keys = append(keys, k)
		}
	}
	slices.Sort(keys)
	var out []string
	for _, k := range keys {
		if g[k] != w[k] {
			out = append(out, k+"\n   server: "+g[k]+"\n   vector: "+w[k])
		}
	}
	return strings.Join(out, "\n")
}

// comparedDecision: the decision types a case's expected decisions list, and
// the identity decisions, which a case without identity reconciliation never
// lists (so a case where Go makes one disagrees visibly).
func comparedDecision(t string) bool {
	switch {
	case strings.HasPrefix(t, "queue."), strings.HasPrefix(t, "episode."):
		return true
	}
	return t == "catalog.refresh" || t == "discovery.admission" || t == "podcast.moved" || t == "podcast.merge"
}

// vectorChoice: the decision types whose server choices a vector records
// (docs/CONTRACT.md "Server decisions", "Catalog, discovery and server
// fetches").
func vectorChoice(t string) bool {
	return strings.HasPrefix(t, "queue.") || t == "catalog.refresh" || t == "discovery.admission" || t == "podcast.moved" ||
		strings.HasPrefix(t, "episode.") || t == "podcast.merge"
}

// padLog appends empty commits until the account's head reaches seq; a
// negative seq pads nothing.
func padLog(t *testing.T, store *storage.Store, account string, seq int64) {
	for {
		done := false
		err := store.Write(context.Background(), func(tx *storage.WriteTx) error {
			acct := tx.Account(account)
			h, err := acct.Head()
			if err != nil || h.Seq >= seq {
				done = true
				return err
			}
			_, _, err = acct.AppendCommit(storage.CommitBody{})
			return err
		})
		if err != nil {
			t.Fatal(err)
		}
		if done {
			return
		}
	}
}

// vectorFetches replays a vector's server fetches (docs/CONTRACT.md
// "Catalog, discovery and server fetches"): a fetch_start captures the
// refresh context (CaptureRefresh); a fetch applies its result in one server
// commit (ApplyServerFetch), with the refresh status computed by
// RefreshStatus; a re-parse names the bases its podcast's stored response
// stands for.
type vectorFetches struct {
	t           *testing.T
	store       *storage.Store
	svc         *protocol.Service
	account     string
	namespace   string
	pending     map[string]startedFetch // refresh ID → what the fetch started under
	stored      map[string]*storedFetch // podcast → its last successful fetch
	lastSuccess map[string]int64        // podcast → its last successful fetch time
}

// storedFetch is a podcast's stored response (PROTOCOL §9.6): its fetch, and the
// revision each of its records stands for (the part that wrote it, else the
// canonical revision when it applied).
type storedFetch struct {
	refreshID string
	fetchTime int64
	revs      map[string]string
}

func (v *vectorFetches) start(fs map[string]any) {
	var f startedFetch
	err := v.svc.ServerCommit(context.Background(), v.account, func(c *protocol.ApplyContext) error {
		var err error
		f, err = captureFetch(c, fs["podcast_id"].(string))
		return err
	})
	if err != nil {
		v.t.Fatal(err)
	}
	v.pending[fs["refresh_id"].(string)] = f
}

// startedFetch is what a fetch captures when it starts: its refresh context
// and, without a live generation, the latest one.
type startedFetch struct {
	rc     RefreshContext
	latest string
}

func captureFetch(c *protocol.ApplyContext, podcast string) (startedFetch, error) {
	rc, err := CaptureRefresh(c, podcast)
	if err != nil || rc.GenerationID != "" {
		return startedFetch{rc: rc}, err
	}
	latest, err := latestGeneration(c, podcast)
	return startedFetch{rc, latest}, err
}

func (v *vectorFetches) apply(i int, fx map[string]any) {
	t := v.t
	R, P, outcome := fx["refresh_id"].(string), fx["podcast_id"].(string), fx["outcome"].(string)
	num := func(x any) (int64, bool) {
		n, ok := x.(json.Number)
		if !ok {
			return 0, false
		}
		i, err := n.Int64()
		return i, err == nil
	}
	var feedFields map[string]any
	var items []ServerItem
	if f, ok := fx["feed"].(map[string]any); ok {
		feedFields = f
		for _, x := range fx["items"].([]any) {
			it := x.(map[string]any)
			items = append(items, ServerItem{Occurrence: it["occurrence"].(map[string]any), Fields: it["fields"].(map[string]any)})
		}
	}
	fetchTime, _ := num(fx["fetch_time"])
	head := v.head()
	// The revision each record of a successful parse stands at, by the
	// episode the server derived (the stored response's bases for a re-parse).
	var revisions map[string]string
	err := v.svc.ServerCommit(context.Background(), v.account, func(c *protocol.ApplyContext) error {
		start, started := v.pending[R]
		delete(v.pending, R)
		if !started && outcome != "re-parse" {
			var err error
			if start, err = captureFetch(c, P); err != nil {
				return err
			}
		}
		rc := start.rc
		x := ServerFetch{PodcastID: P, RefreshID: R, Namespace: c.Namespace, FetchTime: fetchTime}
		var o *FetchOutcome
		switch outcome {
		case "re-parse":
			st := v.stored[P]
			if st == nil || st.refreshID != fx["reparse_of"] {
				t.Fatalf("arrival %d: a re-parse of an unknown stored response", i)
			}
			x.Reparse, x.FetchTime, x.Bases, x.FeedFields, x.Items = true, st.fetchTime, st.revs, feedFields, items
		default:
			x.GenerationID, x.LatestGenerationID, x.RefreshBy, x.Bases = rc.GenerationID, start.latest, rc.RefreshBy, rc.Bases
			o = &FetchOutcome{FetchTime: fetchTime}
			if n, ok := num(fx["next_attempt"]); ok {
				o.NextAttempt = &n
			}
			if s, ok := v.lastSuccess[P]; ok {
				o.LastSuccess = &s
			}
			if outcome == "failure" {
				o.Error = fx["error"].(map[string]any)
				break
			}
			x.FeedFields, x.Items = feedFields, items
			x.Revisions = func(r map[string]string) { revisions = r }
			rds, _ := fx["redirects"].([]any)
			for _, rd := range rds {
				if st, _ := num(rd.(map[string]any)["status"]); st == 301 || st == 308 {
					x.Aliases = append(x.Aliases, rd.(map[string]any)["location"].(string))
				}
			}
			if nf, ok := fx["new_feed_url"].(string); ok {
				x.Aliases, x.NewFeedURL, x.Move = append(x.Aliases, nf), nf, nf
			} else if m, ok := fx["moved_to"].(string); ok {
				x.Move = m
			}
			if m, ok := fx["moved_to"].(string); ok {
				x.MovedTo = m
			}
		}
		if o != nil {
			cur, err := RefreshStatusRecord(c.Account, P)
			if err != nil {
				return err
			}
			if s, due := RefreshStatus(cur, *o); due {
				x.Status = s
			} else {
				x.CurrentStatus = s
			}
		}
		return ApplyServerFetch(c, x)
	})
	if err != nil {
		t.Fatalf("arrival %d: %v", i, err)
	}
	// The parts this fetch wrote: record → part.
	written := map[string]string{}
	err = v.store.Read(context.Background(), func(r *storage.ReadTx) error {
		acct := r.Account(v.account)
		commits, err := acct.Commits(head, head+1, 1)
		if err != nil || len(commits) == 0 {
			return err
		}
		cm, err := contract.DecodeJSON(commits[0].Canonical)
		if err != nil {
			return err
		}
		for _, d := range cm.(map[string]any)["decisions"].([]any) {
			dm := d.(map[string]any)
			if dm["decision_type"] != "catalog.refresh" {
				continue
			}
			res := dm["result"].(map[string]any)
			id := dm["decision_id"].(string)
			if _, ok := res["feed"]; ok {
				written["feed"] = id
			}
			for _, x := range res["items"].([]any) {
				written[x.(map[string]any)["episode_id"].(string)] = id
			}
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	switch outcome {
	case "success":
		v.lastSuccess[P] = fetchTime
		st := &storedFetch{refreshID: R, fetchTime: fetchTime, revs: map[string]string{}}
		maps.Copy(st.revs, revisions)
		maps.Copy(st.revs, written)
		v.stored[P] = st
	case "re-parse":
		maps.Copy(v.stored[P].revs, written)
	}
}

// head is the account's head seq.
func (v *vectorFetches) head() int64 {
	var seq int64
	v.store.Read(context.Background(), func(r *storage.ReadTx) error {
		h, err := r.Account(v.account).Head()
		seq = h.Seq
		return err
	})
	return seq
}

// vectorRandom replays a vector's recorded server choices (docs/CONTRACT.md
// "Server decisions"): each decision of a recorded type takes its ID,
// position IDs and draw from the arrival's `decisions` list, strictly in
// creation order. A mismatch is reported and the server's choice made at
// random, so the rest of the case is still compared.
type vectorRandom struct {
	t       *testing.T
	free    bool // choices the vector cannot record: drawn at random
	arrival int
	// allocated: the choices whose occurrence_id an allocation took
	allocated map[int]bool
	choices   []any
	cur       int // the choice of the decision being made
	pos       int // position IDs used by it
}

func (v *vectorRandom) load(arrival int, choices any) {
	v.arrival, v.cur, v.pos, v.allocated = arrival, 0, 0, nil
	v.choices, _ = choices.([]any)
}

func (v *vectorRandom) current() map[string]any {
	if v.cur >= len(v.choices) {
		return nil
	}
	return v.choices[v.cur].(map[string]any)
}

func (v *vectorRandom) done() {
	if v.cur != len(v.choices) {
		var rest []string
		for _, c := range v.choices[v.cur:] {
			rest = append(rest, c.(map[string]any)["decision_type"].(string))
		}
		v.t.Errorf("arrival %d: the vector records decisions the server did not make: %s", v.arrival, strings.Join(rest, ", "))
	}
}

func randomUUID() string {
	var u [16]byte
	cryptorand.Read(u[:])
	return formatUUID(u)
}

func (v *vectorRandom) DecisionID(decisionType string) string {
	if decisionType == "occurrence" {
		// An allocated release's e0: ID (PROTOCOL §9.7): the recorded occurrence_id
		// of the next mapping that has one, taken before the mapping decision
		// itself (the server allocates it while it reads the item, before the
		// fetch's catalog.refresh part 0 that docs/CONTRACT.md lists first).
		for j := v.cur; j < len(v.choices); j++ {
			c := v.choices[j].(map[string]any)
			if id, ok := c["occurrence_id"].(string); ok && !v.allocated[j] {
				if v.allocated == nil {
					v.allocated = map[int]bool{}
				}
				v.allocated[j] = true
				return id
			}
		}
		v.t.Errorf("arrival %d: the server allocates an occurrence ID the vector does not record", v.arrival)
		return randomUUID()
	}
	if decisionType == "podcast.resolution" {
		// A live registration's resolution is implicit unless the arrival
		// records its ID, as its next choice (docs/CONTRACT.md "Recovery"): the
		// arrival's later facts may then name it.
		if c := v.current(); c != nil && !v.free && c["decision_type"] == decisionType {
			v.cur++
			v.pos = 0
			return c["decision_id"].(string)
		}
		return randomUUID()
	}
	if !vectorChoice(decisionType) || v.free {
		return randomUUID()
	}
	c := v.current()
	if c == nil || c["decision_type"] != decisionType {
		// Find it later in the list (the server skipped choices), else none.
		for j := v.cur + 1; j < len(v.choices); j++ {
			if v.choices[j].(map[string]any)["decision_type"] == decisionType {
				v.t.Errorf("arrival %d: server made %s where the vector records %v", v.arrival, decisionType, c["decision_type"])
				v.cur, v.pos = j, 0
				return v.DecisionID(decisionType)
			}
		}
		v.t.Errorf("arrival %d: server made a %s decision the vector does not record", v.arrival, decisionType)
		v.pos = 0
		return randomUUID()
	}
	if ids, ok := c["position_ids"].([]any); ok && v.pos != len(ids) {
		v.t.Errorf("arrival %d: sort result used %d fresh position IDs, vector records %d", v.arrival, v.pos, len(ids))
	}
	v.cur++
	v.pos = 0
	return c["decision_id"].(string)
}

func (v *vectorRandom) PositionID() [16]byte {
	if v.free {
		var u [16]byte
		cryptorand.Read(u[:])
		return u
	}
	c := v.current()
	var s string
	if ids, ok := c["position_ids"].([]any); ok && v.pos < len(ids) {
		s = ids[v.pos].(string)
	} else if p, ok := c["position_id"].(string); ok && v.pos == 0 {
		s = p
	}
	v.pos++
	u, ok := parsePositionID(s)
	if !ok {
		v.t.Errorf("arrival %d: the server needs a position ID the vector does not record", v.arrival)
		cryptorand.Read(u[:])
	}
	return u
}

func (v *vectorRandom) Index(n int) int {
	draw, ok := v.current()["draw"].(json.Number)
	if !ok {
		v.t.Errorf("arrival %d: random enqueue without a recorded draw", v.arrival)
		return 0
	}
	d, _ := draw.Int64()
	if d < 0 || int(d) >= n {
		v.t.Errorf("arrival %d: recorded draw %d outside [0, %d)", v.arrival, d, n)
		return 0
	}
	return int(d)
}
