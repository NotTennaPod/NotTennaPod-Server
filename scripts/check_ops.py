#!/usr/bin/env python3
"""Serial, inventory-checked ops executions for make check (Python stdlib only)."""

import argparse
from collections import Counter
from datetime import datetime, timezone
import hashlib
import json
import math
import os
from pathlib import Path
import re
import shlex
import signal
import subprocess
import sys
import time
import uuid


OPS = "github.com/NotTennaPod/NotTennaPod-Server/internal/ops"
RULE_PARENT = "TestRuleVectors"
LOAD_SKIPS = {
    "TestUnsubscribeManyEpisodeScopes": "load test (make check runs it without the race detector)",
    "TestHistoryClearAndResetLoad": "load test (make check runs it without the race detector)",
    "TestLongOfflineSessionUpload": "load test (make check runs it without the race detector)",
    "TestRebuildLoad": "load test (make check runs it without the race detector)",
    "TestRotationPerformance": "load test",
    "TestSortedAddWithLongQueueHistory": "load test (make check runs it without the race detector)",
    "TestConcentratedHistoryIsStaged": "load test",
    "TestQueueEditWorkBudget": "load test (make check runs it without the race detector)",
}
MEASURE = "TestQueueReplayMeasure"
MEASURE_SKIP = "set NTP_QUEUE_MEASURE to the number of queue commands"
LOAD_OVERRIDES = (
    "NTP_LISTEN_LOAD", "NTP_REBUILD_LOAD", "NTP_REBUILD_EPISODES",
    "NTP_REBUILD_STAGING", "NTP_IDENTITY_PERF", "NTP_QUEUE_BUDGET_MAX",
)
TOPS_PER_SHARD = 8
CASES_PER_SHARD = 24
ARRIVALS_PER_SHARD = 384

# This small source contract deliberately fails if TestRuleVectors changes its
# discovery algorithm. New files/cases in these roots need no runner edits; a
# new root or naming algorithm must be reflected here rather than silently lost.
RULE_DISCOVERY = '''
files, _ := filepath.Glob("../../contract/vectors/rules_*.json")
// Server-only cases (generated by the reference) beside the shared ones.
more, _ := filepath.Glob("testdata/*/rules_*.json")
files = append(files, more...)
if dir := os.Getenv("NTP_RULE_CASES"); dir != "" {
more, _ := filepath.Glob(filepath.Join(dir, "*.json"))
files = append(files, more...)
}
if len(files) == 0 {
t.Skip("no rule vectors yet")
}
'''


class CheckFailure(Exception):
    pass


def require(condition, message):
    if not condition:
        raise CheckFailure(message)


def go_escape(name):
    """regexp.QuoteMeta, not Python's broader re.escape (Go uses RE2)."""
    return "".join("\\" + c if c in r"\.+*?()|[]{}^$" else c for c in name)


def selector(names, parent=None):
    require(bool(names), "refusing an empty test selector")
    pattern = "^(?:" + "|".join(go_escape(n) for n in sorted(names)) + ")$"
    return "^" + go_escape(parent) + "$/" + pattern if parent else pattern


def top_shards(names):
    """Round-robin sorted inventory: even counts, no historical method list."""
    count = math.ceil(len(names) / TOPS_PER_SHARD)
    return [sorted(names)[i::count] for i in range(count)] if count else []


def rule_shards(cases):
    """Balance arrival work, bounded by both case count and arrival count."""
    count = max(math.ceil(len(cases) / CASES_PER_SHARD),
                math.ceil(sum(c["weight"] for c in cases) / ARRIVALS_PER_SHARD))
    bins = [{"cases": [], "weight": 0} for _ in range(count)]
    for case in sorted(cases, key=lambda c: (-c["weight"], c["name"])):
        choices = [b for b in bins if len(b["cases"]) < CASES_PER_SHARD
                   and (not b["cases"] or b["weight"] + case["weight"] <= ARRIVALS_PER_SHARD)]
        if not choices:
            bins.append({"cases": [], "weight": 0})
            choices = [bins[-1]]
        target = min(choices, key=lambda b: (b["weight"], len(b["cases"])))
        target["cases"].append(case["name"])
        target["weight"] += case["weight"]
    return [sorted(b["cases"]) for b in bins if b["cases"]]


def rule_inventory(root, env):
    source = (root / "internal/ops/rules_test.go").read_text()
    start = source.split("func TestRuleVectors(t *testing.T) {", 1)
    require(len(start) == 2, "cannot locate TestRuleVectors discovery; update runner source contract")
    discovery = start[1].split("for _, file := range files {", 1)
    normalize = lambda s: "\n".join(line.strip() for line in s.splitlines()
                                    if line.strip() and not line.lstrip().startswith("//"))
    require(len(discovery) == 2 and normalize(discovery[0]) == normalize(RULE_DISCOVERY),
            "TestRuleVectors input discovery changed; update runner roots/source contract")
    roots = [(root / "contract/vectors", "rules_*.json", "shared"),
             (root / "internal/ops/testdata", "*/rules_*.json", "server")]
    if env.get("NTP_RULE_CASES"):
        # Go tests execute in the package directory, including for relative env paths.
        extra = Path(env["NTP_RULE_CASES"])
        if not extra.is_absolute():
            extra = root / "internal/ops" / extra
        require(extra.is_dir(), f"NTP_RULE_CASES is not a directory: {extra}")
        roots.append((extra, "*.json", "NTP_RULE_CASES"))
    files, cases, seen = [], [], set()
    for directory, pattern, kind in roots:
        matches = sorted(directory.glob(pattern))
        require(kind != "NTP_RULE_CASES" or matches, "NTP_RULE_CASES selected no JSON inputs")
        for path in matches:
            raw = path.read_bytes()
            suite = json.loads(raw)
            require(isinstance(suite, dict) and isinstance(suite.get("cases"), list)
                    and suite["cases"], f"missing/empty rule cases: {path}")
            record = {"path": str(path.resolve()), "root": kind,
                      "sha256": hashlib.sha256(raw).hexdigest(), "cases": []}
            for index, case in enumerate(suite["cases"]):
                name = f"{path.stem}_{index}"
                # Go rewrites whitespace/non-printable subtest names. Reject these
                # unusual file names explicitly instead of guessing that rewriting.
                require(all(33 <= ord(c) <= 126 and c != "/" for c in name),
                        f"rule filename needs Go name normalization support: {path}")
                require(name not in seen, f"duplicate rule case identifier: {name}")
                require(isinstance(case, dict) and isinstance(case.get("arrivals"), list),
                        f"invalid rule case: {path}:{index}")
                seen.add(name)
                record["cases"].append(name)
                cases.append({"name": name, "weight": max(1, len(case["arrivals"]))})
            files.append(record)
    require(cases, "rule inventory contains no cases")
    return {"roots": [{"path": str(p.resolve()), "glob": g, "kind": k} for p, g, k in roots],
            "files": files, "cases": sorted(cases, key=lambda c: c["name"])}


def json_events(raw):
    events = []
    for line in raw.splitlines():
        if line.strip():
            try:
                event = json.loads(line)
            except ValueError as error:
                raise CheckFailure(f"invalid Go JSON receipt: {line[:160]}") from error
            require(isinstance(event, dict) and "Action" in event, "invalid Go JSON event")
            events.append(event)
    require(events, "Go command emitted no JSON receipts")
    return events


def compiled_inventory(events):
    require(not any(e["Action"] == "fail" for e in events), "compiled discovery failure receipt")
    require(not any(e.get("Test") for e in events), "test bodies ran during compiled discovery")
    require(sum(e.get("Action") == "pass" and e.get("Package") == OPS for e in events) == 1,
            "compiled ops discovery did not pass exactly once")
    names, benchmarks = [], []
    for event in events:
        for line in event.get("Output", "").splitlines():
            if re.fullmatch(r"(?:Test|Example|Fuzz)\S*", line):
                names.append(line)
            elif re.fullmatch(r"Benchmark\S*", line):
                benchmarks.append(line)
    require(names and len(names) == len(set(names)), "compiled inventory is empty or has duplicates")
    require(RULE_PARENT in names, "compiled inventory lacks TestRuleVectors")
    return sorted(names), sorted(benchmarks)


def reconcile(events, tops, bodies, allowed_skips):
    """Validate runs AND terminal receipts, without counting parent wrappers as cases."""
    runs, terminals, outputs = Counter(), {}, {}
    for event in events:
        require(event.get("Action") != "fail", f"Go failure receipt: {event.get('Test', OPS)}")
        test, action = event.get("Test"), event["Action"]
        require(event.get("Package") == OPS, "unexpected package in ops receipts")
        if not test:
            continue
        if action == "output":
            outputs[test] = outputs.get(test, "") + event.get("Output", "")
        if action == "run":
            runs[test] += 1
        if action in ("pass", "skip"):
            require(test not in terminals, f"duplicate terminal receipt: {test}")
            terminals[test] = action
    require(terminals, "no tests selected (no terminal test receipts)")
    require(set(runs) == set(terminals) and all(n == 1 for n in runs.values()),
            "missing/duplicate run or terminal receipts")
    actual_tops = {name for name in terminals if "/" not in name}
    require(actual_tops == set(tops),
            f"top-level coverage mismatch; missing={sorted(set(tops)-actual_tops)}, extra={sorted(actual_tops-set(tops))}")
    actual_bodies = {name.split("/", 1)[1] for name in terminals
                     if name.startswith(RULE_PARENT + "/") and name.count("/") == 1}
    require(actual_bodies == set(bodies),
            f"rule coverage mismatch; missing={sorted(set(bodies)-actual_bodies)}, extra={sorted(actual_bodies-set(bodies))}")
    skips = []
    for name, action in terminals.items():
        require(name.split("/", 1)[0] in tops, f"extra test receipt: {name}")
        if name.startswith(RULE_PARENT + "/"):
            require(name.split("/")[1] in bodies, f"extra rule case receipt: {name}")
        expected = allowed_skips.get(name)
        require(action == ("skip" if expected else "pass"), f"unexpected {action} receipt: {name}")
        if expected:
            require(any(line.endswith(": " + expected) for line in outputs.get(name, "").splitlines()),
                    f"unexpected skip reason: {name}")
            skips.append({"test": name, "reason": expected,
                          "classification": "opt-in measurement" if name == MEASURE else "race load; nonrace required"})
    require(sum(e["Action"] == "pass" and not e.get("Test") for e in events) == 1,
            "ops invocation lacks a unique package PASS")
    return {"tops": sorted(actual_tops), "rule_bodies": sorted(actual_bodies),
            "skips": skips, "terminal_tests": terminals}


class Runner:
    def __init__(self, root, mode, go="go", env=None, case_prefix=None):
        self.root, self.mode = Path(root).resolve(), mode
        self.go = shlex.split(go)
        require(bool(self.go), "empty Go command")
        self.env = dict(os.environ if env is None else env)
        self.case_prefix = case_prefix
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        self.output = self.root / ".work/check-ops" / f"{stamp}-{mode}-{uuid.uuid4().hex[:8]}"
        self.output.mkdir(parents=True)
        self.manifest = {"mode": mode, "status": "running", "invocations": [],
                         "case_prefix": case_prefix, "NTP_RULE_CASES": self.env.get("NTP_RULE_CASES"),
                         "GOFLAGS": self.env.get("GOFLAGS", "")}

    def command(self, label, args):
        command = self.go + args
        extension = "jsonl" if "-json" in args else "stdout"
        record = {"label": label, "command": command, "stdout": f"{label}.{extension}",
                  "stderr": f"{label}.stderr", "exit_code": None}
        self.manifest["invocations"].append(record)
        print(f"check-ops: {label} ({self.output})", flush=True)
        began = time.monotonic()
        with (self.output / record["stdout"]).open("w") as out, (self.output / record["stderr"]).open("w") as err:
            proc = subprocess.Popen(command, cwd=self.root, env=self.env, stdout=out,
                                    stderr=err, start_new_session=True)
            # No run time limit: an invocation runs until it ends.
            try:
                proc.wait()
            except KeyboardInterrupt:
                # Go may have a test child; stop the complete invocation, then retain logs.
                os.killpg(proc.pid, signal.SIGKILL)
                proc.wait()
                raise
            finally:
                record["exit_code"] = proc.returncode
                record["elapsed_seconds"] = round(time.monotonic() - began, 3)
        require(record["exit_code"] == 0, f"Go invocation failed: {label} (exit {record['exit_code']}); see raw logs")
        return (self.output / record["stdout"]).read_text(), record

    def test_args(self, race):
        return ["test"] + (["-race"] if race else []) + ["-count=1", "-timeout", "0", "-json"]

    def discover(self, race):
        label = "compiled-inventory-race" if race else "compiled-inventory-nonrace"
        raw, _ = self.command(label, self.test_args(race) + ["-list", ".", "./internal/ops"])
        names, benchmarks = compiled_inventory(json_events(raw))
        self.manifest.setdefault("compiled_top_inventories", {})["race" if race else "nonrace"] = names
        self.manifest["benchmarks_not_run_by_go_test"] = benchmarks
        return names

    def invoke(self, label, tops, bodies=(), race=False):
        pattern = selector(bodies, RULE_PARENT) if bodies else selector(tops)
        raw, record = self.command(label, self.test_args(race) + ["-run", pattern, "./internal/ops"])
        allowed = {n: LOAD_SKIPS[n] for n in tops if race and n in LOAD_SKIPS}
        if MEASURE in tops:
            allowed[MEASURE] = MEASURE_SKIP
        record["expected_tops"], record["expected_rule_bodies"] = list(tops), list(bodies)
        record["coverage"] = reconcile(json_events(raw), tops, bodies, allowed)

    def run(self):
        try:
            self.execute()
            self.manifest["status"] = "pass"
        except (CheckFailure, OSError, ValueError, KeyboardInterrupt) as error:
            self.manifest["status"] = "fail"
            self.manifest["error"] = str(error) or type(error).__name__
            raise
        finally:
            (self.output / "coverage.json").write_text(json.dumps(self.manifest, indent=2) + "\n")
            print(f"check-ops: {self.manifest['status']}; manifest {self.output / 'coverage.json'}", flush=True)

    def execute(self):
        require(self.case_prefix is None or self.mode == "rules", "case-prefix is only valid for rules mode")
        if self.mode == "other-race":
            raw, _ = self.command("package-inventory", ["list", "-race", "./..."])
            packages = raw.splitlines()
            require(packages.count(OPS) == 1 and len(packages) == len(set(packages)), "invalid package inventory")
            other = [p for p in packages if p != OPS]
            require(other, "no other packages found")
            self.manifest["packages"] = other
            raw, _ = self.command("other-race", self.test_args(True) + ["-run", "."] + other)
            events = json_events(raw)
            require(not any(e["Action"] == "fail" for e in events), "non-ops race failure")
            terminals = Counter(e.get("Package") for e in events
                                if not e.get("Test") and e["Action"] in ("pass", "skip"))
            require(terminals == Counter(other), "non-ops terminal package coverage mismatch")
            for package in other:
                if any(e.get("Package") == package and not e.get("Test") and e["Action"] == "skip" for e in events):
                    require(any(e.get("Package") == package and "[no test files]" in e.get("Output", "") for e in events),
                            f"unclassified non-ops package skip: {package}")
            self.manifest["terminal_package_receipts"] = dict(terminals)
            self.manifest["skip_policy"] = "existing non-ops platform/media/witness semantics"
            return
        require(not self.env.get("NTP_QUEUE_MEASURE"),
                "NTP_QUEUE_MEASURE is opt-in; run TestQueueReplayMeasure separately from make check")
        names = self.discover(self.mode == "race")
        if self.mode == "race":
            require(names == self.discover(False),
                    "race/nonrace compiled test inventories differ; classify build-tag tests explicitly")
        if self.mode == "loads":
            overrides = [n for n in LOAD_OVERRIDES if self.env.get(n)]
            require(not overrides, f"default nonrace loads reject environment overrides: {overrides}")
            require(set(LOAD_SKIPS) <= set(names), "compiled inventory lacks a required default load")
            for name in LOAD_SKIPS:
                self.invoke("load-" + name, [name])
            self.manifest["default_nonrace_loads"] = list(LOAD_SKIPS)
            return
        inventory = rule_inventory(self.root, self.env)
        self.manifest["rule_inventory"] = inventory
        cases = [c for c in inventory["cases"] if self.case_prefix is None or c["name"].startswith(self.case_prefix)]
        require(cases, "rule selection contains no cases")
        self.manifest["excluded_by_case_prefix"] = sorted(set(c["name"] for c in inventory["cases"]) - set(c["name"] for c in cases))
        if self.mode == "race":
            require(set(LOAD_SKIPS) | {MEASURE} <= set(names), "compiled inventory lacks classified load/measurement tests")
            for i, tops in enumerate(top_shards([n for n in names if n != RULE_PARENT])):
                self.invoke(f"top-{i:03d}", tops, race=True)
        for i, bodies in enumerate(rule_shards(cases)):
            self.invoke(f"rules-{i:03d}", [RULE_PARENT], bodies, race=self.mode == "race")
        require(rule_inventory(self.root, self.env) == inventory, "rule inputs changed during execution")
        receipts = [r["coverage"] for r in self.manifest["invocations"] if "coverage" in r]
        body_counts = Counter(n for r in receipts for n in r["rule_bodies"])
        require(body_counts == Counter(c["name"] for c in cases), "aggregate missing/extra/duplicate rule bodies")
        top_counts = Counter(n for r in receipts for n in r["tops"] if n != RULE_PARENT)
        expected_tops = [n for n in names if n != RULE_PARENT] if self.mode == "race" else []
        require(top_counts == Counter(expected_tops), "aggregate missing/extra/duplicate top methods")
        self.manifest["unique_rule_body_receipts"] = sorted(body_counts)
        self.manifest["unique_non_rule_top_receipts"] = sorted(top_counts)
        self.manifest["rule_parent_setup_receipts"] = sum(RULE_PARENT in r["tops"] for r in receipts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("other-race", "race", "rules", "loads"))
    parser.add_argument("--go", default="go", help="Go executable/command, as selected by Makefile GO")
    parser.add_argument("--case-prefix", help="explicit subset for the existing recovery phase")
    args = parser.parse_args()
    try:
        Runner(Path(__file__).resolve().parents[1], args.mode, args.go,
               case_prefix=args.case_prefix).run()
    except (CheckFailure, OSError, ValueError, KeyboardInterrupt) as error:
        print(f"check-ops: FAILED: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
